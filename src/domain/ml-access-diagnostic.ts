const knownCodes = new Set([
  "PA_UNAUTHORIZED_RESULT_FROM_POLICIES",
  "FORBIDDEN",
  "forbidden",
  "access_denied",
  "Invalid scopes",
  "invalid_token",
  "invalid_access_token",
  "ABUSE_PREVENTION_ERROR",
  "unauthorized",
]);
export async function safeAccessDiagnostic(
  response: Response,
  path: "/users/me" | "/sites/MLB",
  authenticated: boolean,
) {
  const contentType = response.headers.get("content-type") || "";
  const format = contentType.includes("json")
    ? "json"
    : contentType.includes("html")
      ? "html"
      : "other";
  let text = "";
  // Do not inspect successful account bodies. Error bodies are classified using
  // fixed codes/markers only; never export arbitrary error messages or HTML.
  if (!response.ok) {
    const reader = response.clone().body?.getReader();
    if (reader) {
      let size = 0;
      const decoder = new TextDecoder();
      try {
        while (size <= 16384) {
          const part = await reader.read();
          if (part.done) break;
          size += part.value.byteLength;
          text += decoder.decode(
            part.value.slice(
              0,
              Math.max(0, 16384 - (size - part.value.byteLength)),
            ),
            { stream: true },
          );
        }
        text += decoder.decode();
      } finally {
        void reader.cancel().catch(() => {});
      }
    }
  }
  let body: Record<string, unknown> = {};
  try {
    const parsed: unknown = JSON.parse(text);
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed))
      body = parsed as Record<string, unknown>;
  } catch {}
  const idHeader = (name: string) => {
    const value = response.headers.get(name);
    return value && /^[a-zA-Z0-9_+=/.:\-]{1,220}$/.test(value) ? value : null;
  };
  return {
    resource: path,
    collected_at: new Date().toISOString(),
    http_status: response.status,
    authorization_header_present: authenticated,
    response_format: format,
    known_error_code: knownCodes.has(String(body.code))
      ? body.code
      : knownCodes.has(String(body.error))
        ? body.error
        : null,
    blocked_by: ["PolicyAgent", "OfficeSec"].includes(String(body.blocked_by))
      ? body.blocked_by
      : null,
    cloudfront_seen:
      response.headers.has("x-amz-cf-id") ||
      /Generated by cloudfront/i.test(text),
    cloudfront_error_page:
      /The request could not be satisfied|Generated by cloudfront/i.test(text),
    proxy_denial_header_present:
      response.headers.has("x-denied-reason") ||
      response.headers.has("x-proxy-error"),
    request_id: idHeader("x-request-id"),
    cloudfront_request_id: idHeader("x-amz-cf-id"),
  };
}
